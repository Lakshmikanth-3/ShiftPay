// Copies the compiled MetronomeVault ABI from the Foundry build into src/abi.
import { readFileSync, writeFileSync } from 'node:fs';
const artifact = JSON.parse(readFileSync(new URL('../../contracts/out/MetronomeVault.sol/MetronomeVault.json', import.meta.url)));
writeFileSync(
  new URL('../src/abi/metronomeVault.ts', import.meta.url),
  `// Generated by scripts/sync-abi.mjs from contracts/out. Do not edit.\nexport const metronomeVaultAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
console.log(`synced ${artifact.abi.length} ABI entries`);
writeFileSync(new URL('../../app/vault-abi.json',import.meta.url),JSON.stringify(artifact.abi,null,2)+'\n');
writeFileSync(new URL('../../app/deployment-artifact.json',import.meta.url),JSON.stringify({bytecode:artifact.bytecode.object,compiler:artifact.metadata?JSON.parse(typeof artifact.metadata==='string'?artifact.metadata:JSON.stringify(artifact.metadata)).compiler.version:'0.8.28'},null,2)+'\n');
